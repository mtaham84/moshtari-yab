"""Build the package dependency diagram from Python import statements."""

from __future__ import annotations

import ast
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGES = {
    "apps": ROOT / "apps",
    "need_engine": ROOT / "need_engine",
    "telegram_crawler": ROOT / "telegram_crawler",
    "workers.x_collector": ROOT / "workers" / "x_collector",
    "workers.ig_collector": ROOT / "workers" / "ig_collector",
    "x_ingest": ROOT / "x_ingest",
    "instagram_discovery": ROOT / "instagram_discovery",
    "shared": ROOT / "shared",
    "xray": ROOT / "xray",
    "config": ROOT / "config",
}


def package_for(module: str) -> str | None:
    matches = [name for name in PACKAGES if module == name or module.startswith(name + ".")]
    return max(matches, key=len) if matches else None


def module_name(path: Path) -> str:
    relative = path.relative_to(ROOT).with_suffix("")
    parts = list(relative.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def imports_from(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    current = module_name(path)
    package = current if path.name == "__init__.py" else current.rpartition(".")[0]
    found: set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.update(alias.name for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                relative = "." * node.level + (node.module or "")
                try:
                    target = importlib.util.resolve_name(relative, package)
                except ImportError:
                    continue
            else:
                target = node.module or ""
            if target:
                found.add(target)
            if node.module is None or node.level:
                found.update(f"{target}.{alias.name}" for alias in node.names if alias.name != "*")
    return found


def build_edges() -> set[tuple[str, str]]:
    edges: set[tuple[str, str]] = set()
    for source_package, directory in PACKAGES.items():
        for path in sorted(directory.rglob("*.py")):
            if any(part in {"__pycache__", ".pytest_cache", "tests", "migrations"} for part in path.parts):
                continue
            try:
                targets = imports_from(path)
            except (SyntaxError, UnicodeError) as error:
                raise SystemExit(f"cannot parse {path.relative_to(ROOT)}: {error}") from error
            for target in targets:
                target_package = package_for(target)
                if target_package and target_package != source_package:
                    edges.add((source_package, target_package))
    return edges


def build_config_names() -> set[str]:
    path = ROOT / "need_engine" / "config.py"
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    names = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
            continue
        if node.func.id == "_f" and node.args and isinstance(node.args[0], ast.Constant):
            names.add(str(node.args[0].value))
    return names


def render(edges: set[tuple[str, str]]) -> str:
    lines = ["# Import dependency graph", "", "Generated by `python scripts/import_graph.py`. Edges come from Python `import` and `from ... import` statements parsed with `ast`.", "", "```mermaid", "graph TD"]
    ids = {name: "pkg_" + name.replace(".", "_") for name in PACKAGES}
    for name in PACKAGES:
        lines.append(f"    {ids[name]}[\"{name}\"]")
    for source, target in sorted(edges):
        lines.append(f"    {ids[source]} --> {ids[target]}")
    lines.extend(["```", "", f"Edges: {len(edges)}.", ""])
    return "\n".join(lines)


def main() -> None:
    destination = ROOT / "docs" / "architecture" / "dependency-graph.md"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(render(build_edges()), encoding="utf-8")
    print(f"Wrote {destination.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
