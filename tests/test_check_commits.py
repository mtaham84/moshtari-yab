"""Tests for scripts/check_commits.py against real temporary git repositories."""
from __future__ import annotations

import zlib
from pathlib import Path

import pytest

from scripts import check_commits


class TestCheckCommits:
    @pytest.fixture(autouse=True)
    def _git(self, git):
        self.git = git

    def commit(self, repo: Path, message: str) -> None:
        name = f"f{zlib.crc32(message.encode())}.txt"   # one file per commit: merges never conflict
        (repo / name).write_text(message, encoding="utf-8")
        self.git(repo, "add", name)
        self.git(repo, "commit", "-q", "-m", message)

    def check(self, repo: Path) -> int:
        return check_commits.main(["main..HEAD", str(repo)])

    @pytest.fixture
    def branch(self, repo: Path) -> Path:
        self.commit(repo, "chore: initial")
        self.git(repo, "switch", "-q", "-c", "feature")
        return repo

    def test_conventional_commits_pass(self, branch):
        self.commit(branch, "feat(ig): add session expiry check")
        self.commit(branch, "fix!: drop legacy proxy mode\n\nWhy: it leaked the server IP.")
        assert self.check(branch) == 0

    @pytest.mark.parametrize("message", [
        "update stuff",
        "Fix: capitalised type",
        "feature: unknown type",
        "fix(scope) missing colon",
        "fix: " + "x" * 70,
    ])
    def test_bad_subjects_fail(self, branch, message):
        self.commit(branch, message)
        assert self.check(branch) == 1

    @pytest.mark.parametrize("trailer", [
        "Co-Authored-By: Claude Opus <noreply@anthropic.com>",
        "Co-authored-by: Antigravity <bot@example.com>",
        "Generated with [Claude Code](https://claude.com/claude-code)",
        "\U0001F916 Generated by Copilot",
    ])
    def test_ai_attribution_fails(self, branch, trailer):
        self.commit(branch, f"fix: something\n\n{trailer}")
        assert self.check(branch) == 1

    def test_human_co_author_passes(self, branch):
        self.commit(branch, "fix: pair work\n\nCo-authored-by: Taha <taha@example.com>")
        assert self.check(branch) == 0

    def test_merge_commit_subject_is_exempt(self, branch):
        self.commit(branch, "fix: on feature")
        self.git(branch, "switch", "-q", "main")
        self.commit(branch, "docs: on main")
        self.git(branch, "switch", "-q", "feature")
        self.git(branch, "merge", "-q", "--no-edit", "main")
        assert self.check(branch) == 0
